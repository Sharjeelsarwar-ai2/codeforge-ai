# Tool 4: Save project metadata
# ---------------------------------------------------------------------------
@tool("save_project_metadata")
def save_project_metadata(project_path: str, metadata: str) -> str:
    """
    Save project metadata (PRD, design system, sitemap, etc.) as a JSON file
    inside a hidden .codeforge/ folder in the project.

    Args:
        project_path: Absolute path to the project root folder.
        metadata: A JSON string containing any project metadata.
                  If it is not valid JSON it will be stored as raw text.

    Returns:
        Success or error message.
    """
    try:
        root = Path(project_path)
        if not root.exists():
            return f"Error: Project folder not found at {project_path}"

        # Create hidden metadata directory
        meta_dir = root / ".codeforge"
        meta_dir.mkdir(parents=True, exist_ok=True)

        # Try to parse as JSON; fall back to wrapping raw text
        try:
            data = json.loads(metadata)
        except (json.JSONDecodeError, TypeError):
            data = {"raw_text": metadata}

        # Always stamp generation time
        data["generated_at"] = datetime.now().isoformat()
        data["project_path"] = str(root.resolve())

        # Write
        meta_file = meta_dir / "project_meta.json"
        meta_file.write_text(json.dumps(data, indent=2, ensure_ascii=False), encoding="utf-8")

        return f"Project metadata saved to {meta_file}"

    except Exception as e:
        return f"Error saving metadata: {str(e)}"