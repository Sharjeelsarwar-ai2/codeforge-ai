# Tool 2: Generate .gitignore
# ---------------------------------------------------------------------------
@tool("generate_gitignore")
def generate_gitignore(project_path: str) -> str:
    """
    Generate a .gitignore file with standard web-project ignore rules.

    Args:
        project_path: Absolute path to the project root folder.

    Returns:
        Success or error message.
    """
    try:
        root = Path(project_path)
        if not root.exists():
            return f"Error: Project folder not found at {project_path}"

        gitignore_content = """\
# ---- Dependencies ----
node_modules/
vendor/

# ---- Build Output ----
dist/
build/
out/
.next/

# ---- IDE / Editor ----
.vscode/
.idea/
*.swp
*.swo
*~

# ---- OS Files ----
.DS_Store
Thumbs.db
Desktop.ini

# ---- Environment ----
.env
.env.local
.env.*.local

# ---- Logs ----
*.log
npm-debug.log*

# ---- Temp ----
tmp/
temp/
*.tmp

# ---- Python ----
__pycache__/
*.py[cod]
*.egg-info/
venv/
"""

        gitignore_path = root / ".gitignore"
        gitignore_path.write_text(gitignore_content, encoding="utf-8")

        return f".gitignore successfully created at {gitignore_path}"

    except Exception as e:
        return f"Error generating .gitignore: {str(e)}"


