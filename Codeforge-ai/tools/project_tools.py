# Tool 3: ZIP the project
# ---------------------------------------------------------------------------
@tool("zip_project")
def zip_project(project_path: str) -> str:
    """
    Compress the entire project folder into a .zip file for download.
    The ZIP is saved next to the project folder (inside workspace/).

    Args:
        project_path: Absolute path to the project root folder.

    Returns:
        Absolute path to the created .zip file, or an error message.
    """
    try:
        root = Path(project_path)
        if not root.exists():
            return f"Error: Project folder not found at {project_path}"

        # ZIP goes into the same parent directory as the project folder
        zip_path = root.parent / f"{root.name}.zip"

        # Files/folders to skip when zipping
        skip_names = {"__pycache__", ".DS_Store", ".git", "node_modules"}

        with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as zf:
            for file_path in root.rglob("*"):
                if file_path.is_file() and file_path.name not in skip_names:
                    # Store paths relative to the project's parent so the
                    # top-level folder inside the ZIP is the project name
                    arcname = file_path.relative_to(root.parent)
                    zf.write(file_path, arcname)

        size_kb = zip_path.stat().st_size / 1024
        return f"ZIP created at {zip_path.resolve()} ({size_kb:.1f} KB)"

    except Exception as e:
        return f"Error creating ZIP: {str(e)}"


